#!/usr/bin/env python3
"""Generates the decoder tests from the encoding tests.

Each encoding test (rust/riscv64/tests.rs) pins an instruction word against an independent
assembler and names the assembly line in its first comment; the decoder must give that line
back. Where two spellings encode the same word (an instruction and its pseudo-instruction,
e.g. `xori rd, rs, -1` and `not rd, rs`), the decoder gives objdump's pseudo-instruction:
ALIASES maps the test's line to it.

    python3 rust/disasm/gen_tests.py > rust/disasm/riscv_tests.rs
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# the canonical (objdump) spelling of a test's line, where it differs
ALIASES = [
    (r"^xori (\w+), (\w+), -1$", r"not \1, \2"),
    (r"^jal zero, (-?\d+)$", r"j \1"),
]


def cases(path):
    src = path.read_text()
    tests = re.findall(r"(#\[ignore[^\]]*\]\s*)?#\[test\]\s*fn (\w+)\(\) \{(.*?)\n\}", src, re.S)
    for ignored, name, body in tests:
        if ignored:
            continue
        comments = re.findall(r"^\s*// (.*)$", body, re.M)
        words = re.findall(r"assert_eq!\(w, (0x[0-9a-f]+)\)", body)
        if len(words) != 1 or not comments:
            sys.exit(f"{name}: expected one word and a comment")
        text = comments[0].strip()
        for pattern, canonical in ALIASES:
            text = re.sub(pattern, canonical, text)
        yield name, int(words[0], 16), text


def main():
    rows = list(cases(ROOT / "rust/riscv64/tests.rs"))
    print("// Generated by rust/disasm/gen_tests.py from the encoding tests in rust/riscv64/tests.rs:")
    print("// do not edit. Each case is (test, word, the assembly line the word encodes).")
    print()
    print("use super::riscv::{decode_word, format};")
    print()
    print("const CASES: &[(&str, u32, &str)] = &[")
    for name, word, text in rows:
        print(f'    ("{name}", 0x{word:08x}, "{text}"),')
    print("];")
    print()
    print("""#[test]
fn riscv_decodes_the_encoding_tests() {
    let mut wrong = Vec::new();
    for (name, word, text) in CASES {
        let got = decode_word(*word).map(|ins| format(&ins));
        if got.as_deref() != Some(*text) {
            wrong.push(format!(
                "{}: 0x{:08x} expected {:?}, got {:?}",
                name, word, text, got
            ));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} cases:\\n{}",
        wrong.len(),
        CASES.len(),
        wrong.join("\\n")
    );
}""")


main()
