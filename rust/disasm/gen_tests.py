#!/usr/bin/env python3
"""Generates the decoder tests from the encoding tests.

Each encoding test (rust/riscv64/tests.rs, rust/arm/tests.rs) pins an instruction word against an
independent assembler (GNU as, Keystone, Capstone) and names the assembly line in its first
comment; the decoder must give that line back. Where the decoder's spelling differs (two
spellings of one word, e.g. `xori rd, rs, -1` and `not rd, rs`; or a spelling that `as` would
encode differently, e.g. RISC-V `mv`, which `as` assembles to `addi`), ALIASES maps the test's
line to the decoder's.

    python3 rust/disasm/gen_tests.py riscv > rust/disasm/riscv_tests.rs
    python3 rust/disasm/gen_tests.py arm > rust/disasm/arm_tests.rs
    python3 rust/disasm/gen_tests.py x86 > rust/disasm/x86_tests.rs

The x86 tests (rust/amd/tests.rs) pin byte strings; their lines are GNU as Intel syntax, but
where the encoder's bytes are not what `as` makes of the line (a redundant REX.W, a longer
form), the decoder adds the pseudo-prefix or `.insn` that gives them. So the x86 test compares
the lines without pseudo-prefixes, spacing and number bases, and, where `as` is installed,
assembles the decoder's text and compares the bytes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

ARCHS = {
    "riscv": {
        "tests": "rust/riscv64/tests.rs",
        "module": "riscv",
        "aliases": [
            (r"^xori (\w+), (\w+), -1$", r"not \1, \2"),
            (r"^jal zero, (-?\d+)$", r"j \1"),
            # `mv` assembles to `addi rd, rs, 0`; symjit's is `add rd, rs, zero`
            (r"^mv (\w+), (\w+)$", r"add \1, \2, zero"),
        ],
    },
    "arm": {
        "tests": "rust/arm/tests.rs",
        "module": "arm",
        "aliases": [
            # the tests' notes on where the expected word came from
            (r"\s+\[expected word from [^\]]*\]$", ""),
            # 0.0 is no FP8 immediate: the macro's word is `movi v<n>.16b, #0`
            (r"^fmov (d|v)(\d+)(\.2d)?, #0\.0$", r"movi v\2.16b, #0"),
            # size 00 of REV64 is bytes (Capstone writes .2d)
            (r"^rev64 v(\d+)\.2d, v(\d+)\.2d$", r"rev64 v\1.16b, v\2.16b"),
            # the rotation of fcadd in decimal, as `as` writes it
            (r"^(fcadd .*), #0x5a$", r"\1, #90"),
            (r"^(fcadd .*), #0x10e$", r"\1, #270"),
        ],
    },
}


def cases(arch):
    src = (ROOT / arch["tests"]).read_text()
    tests = re.findall(r"(#\[ignore[^\]]*\]\s*)?#\[test\]\s*fn (\w+)\(\) \{(.*?)\n\}", src, re.S)
    for ignored, name, body in tests:
        if ignored:
            continue
        comments = re.findall(r"^\s*// (.*)$", body, re.M)
        words = re.findall(r"assert_eq!\(w, (0x[0-9a-fA-F]+)\)", body)
        if len(words) != 1 or not comments:
            sys.exit(f"{name}: expected one word and a comment")
        text = comments[0].strip()
        for pattern, canonical in arch["aliases"]:
            text = re.sub(pattern, canonical, text)
        yield name, int(words[0], 16), text


def x86_cases():
    src = (ROOT / "rust/amd/tests.rs").read_text()
    tests = re.findall(r"(#\[ignore[^\]]*\]\s*)?#\[test\]\s*fn (\w+)\(\) \{(.*?)\n\}", src, re.S)
    for ignored, name, body in tests:
        if ignored:
            continue
        comments = re.findall(r"^\s*// (.*)$", body, re.M)
        m = re.search(r"(check|check_label)\(\s*DataType::\w+,\s*&\[([^\]]*)\]", body, re.S)
        if not m or not comments:
            sys.exit(f"{name}: expected a check and a comment")
        words = [int(x.strip(), 16) for x in m.group(2).split(",") if x.strip()]
        yield name, m.group(1) == "check_label", words, comments[0].strip()


def x86_main():
    rows = list(x86_cases())
    print("// Generated by rust/disasm/gen_tests.py from the encoding tests in rust/amd/tests.rs:")
    print("// do not edit. Each case is (test, label 200 bytes after it, bytes, the assembly line).")
    print()
    print("use super::x86::{decode, format, format_insn};")
    print()
    print("#[rustfmt::skip]")
    print("const CASES: &[(&str, bool, &[u8], &str)] = &[")
    for name, label, words, text in rows:
        b = ", ".join(f"0x{w:02x}" for w in words)
        text = text.replace("\\", "\\\\").replace('"', '\\"')
        print(f'    ("{name}", {str(label).lower()}, &[{b}], "{text}"),')
    print("];")
    print((ROOT / "rust/disasm/x86_tests.tail.rs").read_text(), end="")


def main():
    key = sys.argv[1]
    if key == "x86":
        return x86_main()
    arch = ARCHS[key]
    rows = list(cases(arch))
    print(f"// Generated by rust/disasm/gen_tests.py from the encoding tests in {arch['tests']}:")
    print("// do not edit. Each case is (test, word, the assembly line the word encodes).")
    print()
    print(f"use super::{arch['module']}::{{decode_word, format}};")
    print()
    print("#[rustfmt::skip]")
    print("const CASES: &[(&str, u32, &str)] = &[")
    for name, word, text in rows:
        print(f'    ("{name}", 0x{word:08x}, "{text}"),')
    print("];")
    print()
    print(f"""#[test]
fn {key}_decodes_the_encoding_tests() {{
    let mut wrong = Vec::new();
    for (name, word, text) in CASES {{
        let got = decode_word(*word).map(|ins| format(&ins));
        if got.as_deref() != Some(*text) {{
            wrong.push(format!(
                "{{}}: 0x{{:08x}} expected {{:?}}, got {{:?}}",
                name, word, text, got
            ));
        }}
    }}
    assert!(
        wrong.is_empty(),
        "{{}} of {{}} cases:\\n{{}}",
        wrong.len(),
        CASES.len(),
        wrong.join("\\n")
    );
}}""")


main()
